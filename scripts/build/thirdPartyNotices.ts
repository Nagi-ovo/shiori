import type { Plugin } from "vite";
import { existsSync, readFileSync, readdirSync, type Dirent } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = new URL("../../", import.meta.url);
const NPM_NOTICES = "licenses/npm/LICENSES.md";

export function thirdPartyNotices({ wasmCore }: { wasmCore: boolean }): Plugin {
  return {
    name: "shiori-third-party-notices",
    apply: "build",
    buildStart() {
      this.emitFile({
        type: "asset",
        fileName: "THIRD_PARTY_NOTICES.md",
        source:
          readFileSync(new URL("./THIRD_PARTY_NOTICES.md", REPO_ROOT), "utf8") +
          `\n## npm packages\n\nThe license text of every npm package bundled into this build is in\n\`${NPM_NOTICES}\`, generated when the build runs.\n`,
      });
      // The Word editor bundles harfbuzzjs, a prebuilt HarfBuzz wasm and
      // OFL/GUST fonts; each package carries the texts for what it ships.
      const docxEditor = fileURLToPath(new URL("./node_modules/@docx-editor.dev", REPO_ROOT));
      for (const pkg of ["core", "fonts", "react", "i18n"]) {
        const dir = join(docxEditor, pkg);
        const files = ["LICENSE", "THIRD_PARTY_NOTICES.md"].map((name) => join(dir, name));
        if (existsSync(join(dir, "licenses"))) files.push(...listFiles(join(dir, "licenses")));
        for (const file of files) {
          this.emitFile({
            type: "asset",
            fileName: `licenses/docx-editor/${pkg}/${relative(dir, file).replaceAll("\\", "/")}`,
            source: readFileSync(file),
          });
        }
      }
      // The wasm core ships PDFium and Rust crates; their texts come from
      // scripts/pdfium/build-wasm.ts.
      if (wasmCore) {
        const licenses = fileURLToPath(new URL("./src/pdf/engine/wasm/generated/licenses", REPO_ROOT));
        for (const file of listFiles(licenses)) {
          this.emitFile({
            type: "asset",
            fileName: `licenses/${relative(licenses, file).replaceAll("\\", "/")}`,
            source: readFileSync(file),
          });
        }
      }
    },
    // Minification strips the packages' own license comments, so their
    // notices are collected from what actually landed in the output chunks.
    generateBundle(_options, bundle) {
      this.emitFile({ type: "asset", fileName: NPM_NOTICES, source: npmNotices(Object.values(bundle)) });
    },
  };
}

type BundleItem = { type: string; moduleIds?: readonly string[]; modules?: Record<string, unknown> };

function npmNotices(items: readonly BundleItem[]): string {
  const roots = new Set<string>();
  for (const item of items) {
    if (item.type !== "chunk") continue;
    for (const id of item.moduleIds ?? Object.keys(item.modules ?? {})) {
      const root = packageRoot(id);
      if (root) roots.add(root);
    }
  }
  const sections = [...roots].map(packageSection).sort((a, b) => a.key.localeCompare(b.key));
  return [
    "# npm packages in this build",
    "",
    "Generated by `vite build` from the node_modules packages with code in the",
    "output, with each package's own license and notice files.",
    ...sections.map((section) => `\n${section.text}`),
  ].join("\n");
}

// The package directory a module id belongs to: the path up to the name after
// the last node_modules/, which also covers nested and store-linked copies.
// Virtual (\0) ids and the app's own files have none.
function packageRoot(id: string): string | null {
  if (id.startsWith("\0")) return null;
  const path = id.replaceAll("\\", "/").split("?")[0]!;
  const marker = "/node_modules/";
  const at = path.lastIndexOf(marker);
  if (at < 0) return null;
  const parts = path.slice(at + marker.length).split("/");
  const name = parts[0]?.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
  // node_modules/.vite and friends are tool caches, not packages.
  if (!name || name.startsWith(".")) return null;
  return path.slice(0, at + marker.length) + name;
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-_.][\w.-]*)?$/i;
const NOT_LICENSE_TEXT = /\.(c?js|mjs|d\.ts|ts|json|map)$/i;

function packageSection(root: string): { key: string; text: string } {
  let manifest: { name?: string; version?: string; license?: unknown; licenses?: unknown } = {};
  try {
    manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  } catch {
    // Listed under its directory name with whatever license files it has.
  }
  const name = manifest.name ?? root.slice(root.lastIndexOf("/node_modules/") + "/node_modules/".length);
  const heading = `## ${name}${manifest.version ? ` ${manifest.version}` : ""}`;
  let entries: Dirent[] = [];
  try {
    entries = readdirSync(root, { withFileTypes: true });
  } catch {
    // Not a directory on disk; the heading and declared license still go out.
  }
  const files = entries
    .filter((entry) => entry.isFile() && LICENSE_FILE.test(entry.name) && !NOT_LICENSE_TEXT.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  const vendored = files.length ? [] : vendoredNotices(`${name}@${manifest.version ?? ""}`);
  const body = files.length
    ? files.map((file) => readFileSync(join(root, file), "utf8").trimEnd())
    : vendored.length
      ? vendored
      : ["The package ships no license file; its package.json declares the license above."];
  return {
    key: `${name}\0${manifest.version ?? ""}\0${root}`,
    text: [heading, "", `License: ${declaredLicense(manifest)}`, "", ...body.flatMap((text) => [text, ""])].join("\n"),
  };
}

// Packages whose published archive carries no license file, mapped to the
// texts the CLI's license audit recovered for that exact version (cli/build.ts
// pins @pdf-lib/fontkit 1.1.1 by hash). fontkit's bundle also inlines Brotli
// (Apache-2.0) and other packages whose comments the minifier strips, so their
// notices go out with it. Another version falls back to the declared license.
const VENDORED_NOTICES: Record<string, { dir: string; files: readonly string[] }> = {
  "@pdf-lib/fontkit@1.1.1": {
    dir: "cli/licenses",
    files: ["pdf-lib-fontkit-MIT.txt", "fontkit-bundled-NOTICES.txt", "Apache-2.0.txt", "fontkit-bundle/"],
  },
};

function vendoredNotices(key: string): string[] {
  const entry = VENDORED_NOTICES[key];
  if (!entry) return [];
  const dir = fileURLToPath(new URL(`./${entry.dir}/`, REPO_ROOT));
  return entry.files
    .flatMap((file) => (file.endsWith("/") ? listFiles(join(dir, file)).sort() : [join(dir, file)]))
    .map((path) => `### ${relative(dir, path).replaceAll("\\", "/")}\n\n${readFileSync(path, "utf8").trimEnd()}`);
}

function declaredLicense(manifest: { license?: unknown; licenses?: unknown }): string {
  const name = (value: unknown) =>
    typeof value === "string" ? value : (value as { type?: unknown } | null)?.type;
  const declared = [manifest.license, ...(Array.isArray(manifest.licenses) ? manifest.licenses : [])]
    .map(name)
    .filter((value): value is string => typeof value === "string" && value !== "");
  return declared.length ? declared.join(", ") : "not declared";
}

function listFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listFiles(path));
    else if (entry.isFile()) out.push(path);
  }
  return out;
}
