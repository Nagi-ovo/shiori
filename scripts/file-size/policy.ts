// Keeps hand-written code files under 5,000 tokens (tokens ≈ bytes / 4) so an
// agent can read any one of them whole. Files that were already bigger when
// the gate arrived are listed in baseline.json and may only shrink; the
// pre-commit hook (.githooks/pre-commit → check.ts) applies this to staged files.

export const TOKEN_LIMIT = 5_000;
export const LIMIT_BYTES = TOKEN_LIMIT * 4;
export const BASELINE_PATH = "scripts/file-size/baseline.json";

export const tokens = (bytes: number) => Math.ceil(bytes / 4);

// Only text that people and agents write by hand. Data, prose and binaries are
// out by extension: locale JSON and the changelogs grow by design, and docs are
// split by topic, not by this gate.
const CODE = /\.(ts|tsx|mts|cts|js|jsx|mjs|cjs|rs|kt|kts|java|swift|m|mm|c|h|py|sh|ps1|bat|css|html|ya?ml|toml|gradle)$/;

// Paths whose size someone else decides. Each needs a reason.
const EXCLUDED: { test: (path: string) => boolean; reason: string }[] = [
  {
    // Tauri's `android init` / `ios init` scaffolding and the Kotlin it
    // regenerates. MainActivity.kt is the one file there we write ourselves.
    test: (p) => p.startsWith("src-tauri/gen/") && p !== "src-tauri/gen/android/app/src/main/java/fun/nagi/shiori/MainActivity.kt",
    reason: "Tauri mobile scaffolding",
  },
  { test: (p) => p.startsWith("src-tauri/patches/"), reason: "upstream crates with local patches" },
  { test: (p) => p.startsWith("vendor/"), reason: "vendored tools" },
  { test: (p) => /(^|\/)(fixtures|__fixtures__)\//.test(p), reason: "test data" },
  {
    test: (p) => p === "site/public/cli.sh" || p === "site/public/cli.ps1",
    reason: "assembled from cli/installer by cli/installer/assemble.ts",
  },
  { test: (p) => p === "src/platform/bindings.ts", reason: "generated by tauri-specta (src-tauri/src/lib.rs)" },
];

export function inScope(path: string): boolean {
  return CODE.test(path) && !EXCLUDED.some((e) => e.test(path));
}

export type Change =
  | { status: "A" | "M" | "T"; path: string; bytes: number }
  | { status: "R" | "C"; oldPath: string; path: string; bytes: number }
  | { status: "D"; path: string };

export type Baseline = Record<string, number>;

// A cast would let "30,000" or NaN through, and every comparison against NaN
// is false, which would allow any growth.
export function parseBaseline(text: string): Baseline {
  const value: unknown = JSON.parse(text);
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new Error(`${BASELINE_PATH} must be an object of path -> bytes.`);
  }
  for (const [path, bytes] of Object.entries(value)) {
    if (!Number.isSafeInteger(bytes) || (bytes as number) < 0) {
      throw new Error(`${BASELINE_PATH}: "${path}" must be a whole number of bytes, got ${JSON.stringify(bytes)}.`);
    }
  }
  return value as Baseline;
}

export type Violation = {
  path: string;
  bytes: number;
  allowed: number;
  reason: "over-limit" | "grew" | "baseline-raised";
};

export type Tightened = { path: string; from: number; to: number | null };

export function evaluate(input: {
  changes: Change[];
  headBaseline: Baseline | null;
  stagedBaseline: Baseline | null;
}): { violations: Violation[]; baseline: Baseline; tightened: Tightened[] } {
  const violations: Violation[] = [];
  // HEAD is the authority once the baseline is committed; before that (the
  // commit that introduces it) the staged copy is all there is.
  const head = input.headBaseline ?? input.stagedBaseline ?? {};

  // The staged copy is what the committer asks for: entries may be lowered or
  // removed by hand, never raised or added. An entry already moved to a
  // rename's new path (a commit retried after an abort) counts as the old one.
  const renamedFrom = new Map<string, string>();
  for (const c of input.changes) if (c.status === "R") renamedFrom.set(c.path, c.oldPath);
  const allowance: Baseline = input.stagedBaseline === null ? { ...head } : {};
  for (const [path, bytes] of Object.entries(input.stagedBaseline ?? {})) {
    const source = renamedFrom.get(path);
    const key = !(path in head) && source !== undefined && source in head ? source : path;
    const was = head[key];
    if (was === undefined || bytes > was) {
      violations.push({ path, bytes, allowed: was ?? LIMIT_BYTES, reason: "baseline-raised" });
      if (was !== undefined) allowance[key] = was;
      continue;
    }
    allowance[key] = Math.min(bytes, allowance[key] ?? bytes);
  }

  // Every lookup reads the allowances as they stood before this commit, so the
  // order git lists renames in cannot change the result: a swap, a chain, or a
  // move that leaves a thin re-export at the old path.
  const before = allowance;
  const after: Baseline = { ...before };
  const renamedAway = new Set<string>();
  const copies = new Map<string, number>();
  for (const c of input.changes) {
    if (c.status === "R") renamedAway.add(c.oldPath);
    if (c.status === "C") copies.set(c.oldPath, (copies.get(c.oldPath) ?? 0) + 1);
    if (c.status === "R" || c.status === "D") delete after[c.status === "R" ? c.oldPath : c.path];
  }
  // A file moved out with a thin re-export left behind shows up (git -B -M) as
  // a copy plus a rewrite of the source. The allowance follows the content
  // when the source drops under the limit and there is only the one copy.
  const movedOut = (source: string) =>
    copies.get(source) === 1 &&
    input.changes.some((c) => c.path === source && c.status !== "D" && c.status !== "R" && c.status !== "C" && c.bytes <= LIMIT_BYTES);

  const tightened: Tightened[] = [];
  for (const change of input.changes) {
    if (change.status === "D") continue;
    // A rename keeps its allowance; a copy, or a new file at a path renamed
    // away in this commit, starts from the limit.
    const allowed =
      change.status === "R" || (change.status === "C" && movedOut(change.oldPath))
        ? before[change.oldPath]
        : renamedAway.has(change.path)
          ? undefined
          : before[change.path];
    delete after[change.path];
    if (!inScope(change.path)) continue;
    if (allowed === undefined || allowed <= LIMIT_BYTES) {
      if (change.bytes > LIMIT_BYTES) {
        violations.push({ path: change.path, bytes: change.bytes, allowed: LIMIT_BYTES, reason: "over-limit" });
      }
      continue;
    }
    if (change.bytes > allowed) {
      after[change.path] = allowed;
      violations.push({ path: change.path, bytes: change.bytes, allowed, reason: "grew" });
      continue;
    }
    if (change.bytes <= LIMIT_BYTES) {
      tightened.push({ path: change.path, from: allowed, to: null });
    } else {
      after[change.path] = change.bytes;
      if (change.bytes < allowed) tightened.push({ path: change.path, from: allowed, to: change.bytes });
    }
  }

  const baseline = Object.fromEntries(Object.entries(after).sort(([a], [b]) => (a < b ? -1 : 1)));
  return { violations, baseline, tightened };
}

const fmt = (n: number) => n.toLocaleString("en-US");

export function report(violations: Violation[]): string {
  const lines = [`File size check failed: tokens are bytes / 4, and the limit is ${fmt(TOKEN_LIMIT)} per file.`, ""];
  for (const v of violations) {
    const now = `${fmt(tokens(v.bytes))} tokens (${fmt(v.bytes)} bytes)`;
    const allowed = `${fmt(tokens(v.allowed))} tokens (${fmt(v.allowed)} bytes)`;
    if (v.reason === "over-limit") lines.push(`  ${v.path}: ${now}, limit ${fmt(TOKEN_LIMIT)} tokens`);
    else if (v.reason === "grew")
      lines.push(
        `  ${v.path}: ${now}, allowed ${allowed}. It was already over the limit when this check` +
          ` arrived, so it may stay the same size or shrink, never grow.`,
      );
    else
      lines.push(
        `  ${BASELINE_PATH}: the entry for ${v.path} was raised or added (${fmt(v.bytes)} bytes, allowed` +
          ` ${fmt(v.allowed)}). Entries may be lowered or removed, never raised or added; split the file instead.`,
      );
  }
  lines.push(
    "",
    "How to split a file that is too big:",
    "  1. Find the seams. List the file's top-level units (exported functions, components, classes, hooks,",
    "     Rust impl blocks and modules, describe() blocks) and group them by the one job each group does.",
    "     Each group becomes its own file. Aim well under the limit, not just under it.",
    "  2. Move, don't rewrite. Cut each group into a sibling file named for its job",
    "     (store.ts -> store/history.ts, store/selection.ts; lib.rs -> geometry.rs + `mod geometry;`),",
    "     keep the code as it was, and import what it needs. Shared types and helpers go in their own small file.",
    "  3. Keep callers unchanged. Leave the original path as a thin entry that re-exports the public API",
    "     (TypeScript: `export { … } from \"./store/history.ts\"`; Rust: `pub use geometry::…`).",
    "  4. Split tests by behaviour, not by line count: one <name>.<area>.test.ts per describe() group,",
    "     next to the original (the repo already has OverlayDom.render.test.tsx).",
    "  5. Run `bun run verify`, then stage the new files together with the smaller original and commit again.",
    "",
    "Do not minify, join lines, delete comments or move code into strings to get under the limit, and do not",
    `raise or add entries in ${BASELINE_PATH}. If the file is generated or vendored, add its path to EXCLUDED`,
    "in scripts/file-size/policy.ts with a one-line reason.",
  );
  return lines.join("\n");
}
