/**
 * Builds shiori-core for the web and mobile builds (docs/PLAN-RUST-PDF-CORE-2026-09.md,
 * stage 4.6) into src/pdf/engine/wasm/generated/, which Vite bundles:
 *
 * - shiori_core_wasm.js + _bg.wasm: crates/shiori-core-wasm through the
 *   wasm-bindgen CLI pinned below (installed into vendor/tools/ on first use;
 *   it must equal the crate's wasm-bindgen version or the glue will not load);
 * - pdfium.mjs + pdfium.wasm: PDFium's Emscripten build (scripts/pdfium/fetch.ts),
 *   its classic-script glue wrapped as an ES module function so a module
 *   worker can load it without eval.
 *
 * Run: bun scripts/pdfium/build-wasm.ts   (needs Rust with the wasm32-unknown-unknown target)
 */
import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { copyFile, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { fetchPdfium, PDFIUM_VERSION } from "./fetch";
import { renderRustNotices } from "./rust-notices";

const WASM_BINDGEN_VERSION = "0.2.129";
const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const CRATE = join(REPO_ROOT, "crates", "shiori-core-wasm");
const TOOLS = join(REPO_ROOT, "vendor", "tools");
export const WASM_OUT = join(REPO_ROOT, "src", "pdf", "engine", "wasm", "generated");

function run(command: string, args: string[]): void {
  const result = spawnSync(command, args, { stdio: "inherit", cwd: REPO_ROOT });
  if (result.status !== 0) throw new Error(`${command} ${args.join(" ")} exited ${result.status}`);
}

function wasmBindgen(): string {
  const bin = join(TOOLS, "bin", process.platform === "win32" ? "wasm-bindgen.exe" : "wasm-bindgen");
  const version = existsSync(bin) ? spawnSync(bin, ["--version"], { encoding: "utf8" }).stdout : "";
  if (!version.includes(WASM_BINDGEN_VERSION)) {
    run("cargo", ["install", "wasm-bindgen-cli", "--version", WASM_BINDGEN_VERSION, "--locked", "--root", TOOLS]);
  }
  return bin;
}

/**
 * PDFium's glue is a classic script declaring `var Module`. Wrapped in a
 * function taking `Module`, the declaration keeps the caller's object. Recent
 * Emscripten keeps wasmExports and FS inside the glue's scope; pdfium-render
 * looks for `Module.wasmExports` and the loader writes fonts through `FS`.
 * `require` is only read when the glue runs under Node (tests).
 */
function wrapGlue(glue: string): string {
  return [
    `// Generated by scripts/pdfium/build-wasm.ts from PDFium chromium/${PDFIUM_VERSION}'s Emscripten glue.`,
    "// @ts-nocheck",
    "export default function createPdfiumModule(Module, require) {",
    glue,
    ";",
    'Object.defineProperty(Module, "wasmExports", { get: () => wasmExports });',
    'Object.defineProperty(Module, "FS", { get: () => FS });',
    "return Module;",
    "}",
    "",
  ].join("\n");
}

export async function buildWasm(): Promise<string> {
  const pdfium = join(await fetchPdfium("wasm"), "lib");
  run("cargo", [
    "build", "--release", "--target", "wasm32-unknown-unknown",
    "--manifest-path", join(CRATE, "Cargo.toml"),
  ]);
  await mkdir(WASM_OUT, { recursive: true });
  run(wasmBindgen(), [
    "--target", "web", "--out-dir", WASM_OUT,
    join(CRATE, "target", "wasm32-unknown-unknown", "release", "shiori_core_wasm.wasm"),
  ]);
  await writeFile(join(WASM_OUT, "pdfium.mjs"), wrapGlue(await readFile(join(pdfium, "pdfium.js"), "utf8")));
  await writeFile(
    join(WASM_OUT, "pdfium.d.mts"),
    "export default function createPdfiumModule(Module: Record<string, unknown>, require?: unknown): Record<string, unknown>;\n",
  );
  await copyFile(join(pdfium, "pdfium.wasm"), join(WASM_OUT, "pdfium.wasm"));
  // What the web build distributes with them (vite.config.ts emits these
  // under licenses/): PDFium's third-party texts and the Rust crates' own.
  await mkdir(join(WASM_OUT, "licenses", "pdfium"), { recursive: true });
  for (const file of await readdir(join(pdfium, "..", "licenses"))) {
    await copyFile(join(pdfium, "..", "licenses", file), join(WASM_OUT, "licenses", "pdfium", file));
  }
  await writeFile(
    join(WASM_OUT, "licenses", "rust-crates-NOTICES.txt"),
    renderRustNotices(join(CRATE, "Cargo.toml"), ["wasm32-unknown-unknown"], [
      "Rust crates in the web and mobile builds' wasm core",
      "(crates/shiori-core-wasm). Generated by scripts/pdfium/build-wasm.ts;",
      "each crate's own license files follow its heading.",
    ]),
  );
  return WASM_OUT;
}

if (import.meta.main) {
  console.log(await buildWasm());
}
