/**
 * Writes cli/licenses/rust-crates-NOTICES.txt: the license texts of every
 * Rust crate linked into the CLI's shiori-core addon, on any CLI release
 * target. Compile-time-only crates (proc macros and what only they use) are
 * left out; they are not distributed. `renderRustNotices` also serves the
 * web build's wasm core (scripts/pdfium/build-wasm.ts).
 * Run: bun scripts/pdfium/rust-notices.ts [--check]
 * With --check it exits non-zero when the committed file is stale, which the
 * CLI build runs so a dependency bump cannot ship without its notices.
 */
import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const REPO_ROOT = resolve(import.meta.dir, "../..");
const MANIFEST = join(REPO_ROOT, "crates", "shiori-core-node", "Cargo.toml");
export const RUST_NOTICES_PATH = join(REPO_ROOT, "cli", "licenses", "rust-crates-NOTICES.txt");

/** The Rust targets behind cli/build.ts's SUPPORTED_CLI_TARGETS. */
const RUST_TARGETS = [
  "aarch64-apple-darwin",
  "aarch64-unknown-linux-gnu",
  "x86_64-unknown-linux-gnu",
  "aarch64-pc-windows-msvc",
  "x86_64-pc-windows-msvc",
];

type Package = {
  name: string;
  version: string;
  license: string | null;
  manifest_path: string;
  source: string | null;
  repository: string | null;
};

/**
 * Crates whose published package leaves its license file out, mapped to the
 * upstream repository's own license, copied here after review. napi-rs:
 * github.com/napi-rs/napi-rs LICENSE, blob 7fe7e35e, fetched 2026-09-25.
 */
const UPSTREAM_LICENSES: Record<string, string> = {
  "https://github.com/napi-rs/napi-rs": join(import.meta.dir, "napi-rs-LICENSE.txt"),
};

function cargo(args: string[]): string {
  const run = spawnSync("cargo", args, {
    cwd: REPO_ROOT,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (run.status !== 0) throw new Error(`cargo ${args.join(" ")}: ${run.stderr}`);
  return run.stdout;
}

export function renderRustNotices(
  manifest = MANIFEST,
  targets: readonly string[] = RUST_TARGETS,
  heading = [
    "Rust crates linked into the Shiori CLI's shiori-core addon",
    "(crates/shiori-core-node). Generated by scripts/pdfium/rust-notices.ts;",
    "each crate's own license files follow its heading.",
  ],
): string {
  const MANIFEST_PATH = manifest;
  const shipped = new Set<string>();
  for (const target of targets) {
    const tree = cargo([
      "tree", "--manifest-path", MANIFEST_PATH, "--locked",
      "-e", "normal,no-proc-macro", "--target", target,
      "--prefix", "none", "--format", "{p}",
    ]);
    for (const line of tree.split("\n")) {
      const match = /^(\S+) v(\S+)/.exec(line.trim());
      if (match) shipped.add(`${match[1]}@${match[2]}`);
    }
  }
  const metadata = JSON.parse(
    cargo(["metadata", "--manifest-path", MANIFEST_PATH, "--locked", "--format-version", "1"]),
  ) as { packages: Package[] };
  const packages = metadata.packages
    // Shiori's own crates are not third-party.
    .filter((pkg) => pkg.source !== null && shipped.has(`${pkg.name}@${pkg.version}`))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

  const sections = packages.map((pkg) => {
    const dir = dirname(pkg.manifest_path);
    const files = readdirSync(dir)
      .filter((file) => /^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)/i.test(file))
      .sort();
    const upstream = pkg.repository ? UPSTREAM_LICENSES[pkg.repository] : undefined;
    if (files.length === 0 && !upstream) {
      throw new Error(`${pkg.name} ${pkg.version} ships no license file; review it by hand`);
    }
    const texts =
      files.length > 0
        ? files.map(
            (file) => `--- ${file} ---\n${readFileSync(join(dir, file), "utf8").trimEnd()}\n`,
          )
        : [`--- LICENSE (upstream ${pkg.repository}) ---\n${readFileSync(upstream!, "utf8").trimEnd()}\n`];
    return `=== ${pkg.name} ${pkg.version} (${pkg.license ?? "see files"}) ===\n\n${texts.join("\n")}`;
  });
  return [
    ...heading,
    "",
    ...packages.map((pkg) => `- ${pkg.name} ${pkg.version}: ${pkg.license ?? "see files"}`),
    "",
    ...sections,
  ].join("\n");
}

if (import.meta.main) {
  const rendered = renderRustNotices();
  if (process.argv.includes("--check")) {
    const current = readFileSync(RUST_NOTICES_PATH, "utf8");
    if (current !== rendered) {
      console.error(`${RUST_NOTICES_PATH} is stale; run bun scripts/pdfium/rust-notices.ts`);
      process.exit(1);
    }
  } else {
    writeFileSync(RUST_NOTICES_PATH, rendered);
    console.log(RUST_NOTICES_PATH);
  }
}
