import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const installerDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(installerDir, "..", "..");
const hostedShPath = join(repoRoot, "site", "public", "cli.sh");
const hostedPs1Path = join(repoRoot, "site", "public", "cli.ps1");

const GENERATED_NOTICE = "Generated by bun cli/installer/assemble.ts — do not edit.";

function stripShebang(source: string): string {
  return source.replace(/^#![^\n]*\n/, "");
}

export function assembleHostedInstaller(terminalUi: string, install: string): string {
  return [
    "#!/bin/sh",
    `# ${GENERATED_NOTICE}`,
    "set -eu",
    "SHIORI_INSTALLER_EMBEDDED=1",
    stripShebang(terminalUi).replace(/\s*$/, ""),
    stripShebang(install).replace(/\s*$/, ""),
    "",
  ].join("\n");
}

// The PowerShell installer has nothing to inline — it is one self-contained
// file. It still goes through assembly so `--check` covers both hosted
// scripts and `site/public/` stays entirely generated.
//
// The notice is rewritten to ASCII rather than reused verbatim: this file is
// what `irm | iex` actually executes, and the em dash in GENERATED_NOTICE
// would be the one non-ASCII byte in it.
export function assembleHostedPowershellInstaller(install: string): string {
  const notice = GENERATED_NOTICE.replace("—", "--");
  return [`# ${notice}`, install.replace(/\s*$/, ""), ""].join("\n");
}

async function main(): Promise<void> {
  const check = process.argv.includes("--check");
  const outputs: { path: string; body: string }[] = [
    {
      path: hostedShPath,
      body: assembleHostedInstaller(
        await readFile(join(installerDir, "terminal-ui.sh"), "utf8"),
        await readFile(join(installerDir, "install.sh"), "utf8"),
      ),
    },
    {
      path: hostedPs1Path,
      body: assembleHostedPowershellInstaller(
        await readFile(join(installerDir, "install.ps1"), "utf8"),
      ),
    },
  ];

  for (const output of outputs) {
    if (check) {
      const existing = await readFile(output.path, "utf8").catch(() => "");
      if (existing !== output.body) {
        throw new Error(`${output.path} is stale; run bun cli/installer/assemble.ts`);
      }
      continue;
    }
    await writeFile(output.path, output.body);
    console.log(output.path);
  }
}

if (import.meta.main) {
  void main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
